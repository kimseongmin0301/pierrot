"""수치 없는 방향 주장을 파이썬이 건져 냅니다.

왜 필요한가
-----------
재무 파서(gpt-4o-mini)가 "구체적인 수치가 없다"는 이유로 방향 주장을 계속
OTHER 로 버립니다. 프롬프트에 이렇게까지 적었는데도 그렇습니다.

    "수치가 없다는 이유만으로 OTHER 로 두지 마십시오."
    "꾸밈말(대폭·크게·지속적으로)은 방향을 바꾸지 않습니다. 무시하십시오."

더 나쁜 것은 **일관성이 없다**는 점입니다. 같은 형태인데 하나는 통과하고
하나는 버려집니다.

    "2025년에 매출이 지속적으로 상승하였다"  -> 어떤 실행에서는 DIRECTION
    "2024년에 매출이 대폭 증가하였다"        -> 같은 실행에서 OTHER

프롬프트로 부탁하는 것만으로는 지켜지지 않습니다. 이 프로젝트는 같은 일을
이미 두 번 겪었습니다(다듬기 단계가 없는 회사를 지어낸 건, 주장 개수를
줄인 건). 그때마다 **부탁을 검사로 바꿔서** 해결했습니다.

무엇을 하는가
-------------
파서가 OTHER 로 버린 주장만 다시 봅니다. 아래를 **전부** 만족할 때만
DIRECTION 으로 되살립니다.

    1. 계정 낱말이 있다 (매출 / 영업이익 / 순이익 / EPS ...)
    2. 방향 낱말이 있다 (증가 / 감소 / 흑자 / 적자 ...)
    3. 금액도 증감률도 적혀 있지 않다
    4. 부문·제품 주장이 아니다
    5. 인과 주장이 아니다 ("매출 증가의 원인은 ~이다")

하나라도 어긋나면 손대지 않습니다. 되살리는 쪽보다 **잘못 되살리는 쪽이
훨씬 나쁘기** 때문입니다. 부문 매출을 전사 매출과 견주면 거짓 "근거 있음"이
납니다(실제로 한 번 냈습니다).
"""

from __future__ import annotations

import re

# 계정 낱말 -> 표준 계정 이름. 긴 것부터 맞춰야 "지배주주 순이익"이
# "순이익"으로 잘못 잡히지 않습니다.
ACCOUNT_WORDS: tuple[tuple[str, str], ...] = (
    ("지배주주순이익", "지배주주순이익"),
    ("지배주주 순이익", "지배주주순이익"),
    ("주당순이익", "주당순이익"),
    ("주당 순이익", "주당순이익"),
    ("EPS", "주당순이익"),
    ("주당배당금", "주당배당금"),
    ("주당 배당금", "주당배당금"),
    ("DPS", "주당배당금"),
    ("배당금 총액", "배당금총액"),
    ("배당금총액", "배당금총액"),
    ("영업활동현금흐름", "영업활동현금흐름"),
    ("영업활동 현금흐름", "영업활동현금흐름"),
    ("당기순이익", "당기순이익"),
    ("순이익", "당기순이익"),
    ("영업이익", "영업이익"),
    ("영업손실", "영업이익"),
    ("매출액", "매출액"),
    ("매출", "매출액"),
    ("자산총계", "자산총계"),
    ("부채총계", "부채총계"),
    ("자본총계", "자본총계"),
    ("이익잉여금", "이익잉여금"),
)

# 늘었다는 뜻
UP_WORDS = re.compile(
    r"증가|상승|개선|늘어|늘었|늘렸|확대|성장|호전|흑자\s*전환|흑자로\s*전환"
    r"|높은\s*수준|우수|좋은\s*성장|플러스|긍정적"
)

# 줄었다는 뜻
DOWN_WORDS = re.compile(
    r"감소|하락|악화|줄어|줄었|축소|둔화|부진|적자|역성장|마이너스"
    r"|부정적|낮은\s*수준|후퇴|급감"
)

# 숫자가 적혀 있으면 손대지 않습니다. 금액이나 증감률 주장이므로
# 파서가 AMOUNT / GROWTH 로 다루어야 합니다.
HAS_NUMBER = re.compile(
    r"\d[\d,.]*\s*(조|억|만|천)?\s*(원|달러|유로|엔|%|퍼센트|%p)"
    r"|\d[\d,.]*\s*(조|억)\b"
)

# 인과 주장. 방향이 맞아도 **원인까지 맞은 것은 아닙니다.**
#
# 실측 오탐:
#   "셀트리온 2024년 1분기 매출 증가의 주된 원인은 미국 바이오시밀러 수요 증가이다"
#   -> '매출' + '증가' 를 보고 방향 주장으로 되살렸고, 매출이 실제로 늘었으므로
#      '근거 있음' 이 났습니다. 그러나 **원인이 무엇인지는 아무것도 확인하지
#      않았습니다.** 참인 부분이 들어 있다고 주장 전체가 참이 되지 않습니다.
CAUSAL_WORDS = re.compile(
    r"원인|때문|덕분|덕에|기인|요인|배경|영향을\s*(미쳤|주었|준)|로\s*인해|때문에"
    r"|견인|이끌었|힘입|비롯"
)

# 부문·제품 주장. 전사 수치와 견주면 안 됩니다.
SEGMENT_WORDS = re.compile(
    r"부문|사업부|사업\s*부문|제품별|품목별|지역별"
    r"|HBM|D램|DRAM|낸드|NAND|반도체\s*사업|광고\s*사업|백신\s*사업"
)


def find_account(text: str) -> str:
    """주장에서 표준 계정 이름을 찾습니다. 없으면 빈 문자열."""
    target = text or ""
    for word, account in ACCOUNT_WORDS:
        if word in target:
            return account
    return ""


def find_direction(text: str) -> str:
    """'UP' / 'DOWN' / '' 를 돌려줍니다.

    둘 다 들어 있으면 판단하지 않습니다. "매출은 늘었으나 이익은 줄었다"
    같은 문장은 주장 하나로 다룰 수 없습니다.
    """
    target = text or ""
    up = bool(UP_WORDS.search(target))
    down = bool(DOWN_WORDS.search(target))
    if up and down:
        return ""
    if up:
        return "UP"
    if down:
        return "DOWN"
    return ""


def rescue(text: str) -> tuple[str, str]:
    """(계정, 방향)을 돌려줍니다. 되살릴 수 없으면 ("", "").

    조건을 하나라도 어기면 손대지 않습니다. 되살리지 못해 확인 불가로
    남는 것보다, 잘못 되살려 거짓 판정을 내는 쪽이 훨씬 나쁩니다.
    """
    target = (text or "").strip()
    if not target:
        return "", ""
    if HAS_NUMBER.search(target):
        return "", ""          # 금액·증감률 주장은 파서가 맡습니다
    if SEGMENT_WORDS.search(target):
        return "", ""          # 부문 주장은 전사 수치와 견주면 안 됩니다
    if CAUSAL_WORDS.search(target):
        return "", ""          # 방향이 맞아도 원인까지 맞은 것은 아닙니다

    account = find_account(target)
    direction = find_direction(target)
    if not account or not direction:
        return "", ""
    return account, direction
