"""'좋은 실적을 냈다' 같은 **평가 표현**을 가려냅니다.

왜 막아야 하는가
----------------
평가 표현은 참·거짓을 가릴 대상이 아닙니다. 무엇을 '좋다' 고 할지는
기준에 따라 달라지고, 공시에는 그 기준이 없습니다.

그런데 의미 비교(NLI) 경로로 흘러가면 **0.99대 확신으로 판정**합니다.
실측(가상 샘플 100건):

    "삼바는 2025년에 좋은 실적을 냈다"    -> 근거 있음 (함의 0.998)
    "엘지화학는 2025년에 좋은 실적을 냈다" -> 모순    (모순 0.999)

다섯 건 모두 **함의와 모순이 동시에 0.99 를 넘었습니다**(모순 0.999 > 함의 0.998).
3단계에서 확인한 "오류가 양방향 모두 고확신" 그대로입니다. 어느 쪽으로
갈라져도 근거가 되지 못합니다. 끌어온 근거도 1분기·2분기 단편이었습니다.

무엇을 막고 무엇을 두는가
-------------------------
막는 것은 **잴 수 있는 내용이 전혀 없는 평가 문장**뿐입니다.

    막음: "좋은 실적을 냈다"           (평가어 + 두루뭉술한 명사만)
    둠:   "반도체 부문 실적이 개선되었다"  (부문이라는 잴 대상이 있음)
    둠:   "영업이익이 좋은 흐름을 보였다"  (영업이익이라는 계정이 있음)
    둠:   "실적이 전년 대비 20% 늘었다"   (수치가 있음)

1단계 프롬프트가 "수치가 없다는 이유로 서술 문장을 건너뛰지 말라" 고
못박아 둔 것과 충돌하지 않습니다. 저기서 뽑으라는 것은 **인과·사건**이고
여기서 막는 것은 **값 판단**입니다.
"""

from __future__ import annotations

import re

from .direction_rescue import ACCOUNT_WORDS, HAS_NUMBER, SEGMENT_WORDS

# 값 판단을 나타내는 꾸밈말.
JUDGMENT_WORDS = re.compile(
    r"좋은|좋았|나쁜|나빴|훌륭|우수한|뛰어난|양호|부진|저조|무난|견조|탄탄"
    r"|인상적|긍정적인\s*평가|성공적|만족스러"
)

# 그 꾸밈말이 걸리는 두루뭉술한 명사. 잴 대상이 못 됩니다.
VAGUE_NOUNS = re.compile(r"실적|성과|흐름|모습|분위기|결과|성적|상황|기조")


def is_value_judgment(text: str) -> bool:
    """잴 수 있는 내용이 없는 순수 평가 문장이면 True.

    계정 이름, 부문 이름, 숫자 중 하나라도 있으면 잴 거리가 있는 것이므로
    막지 않습니다. 막는 쪽보다 **잘못 막는 쪽이 나쁩니다** — 확인할 수 있는
    주장을 확인 불가로 버리게 되기 때문입니다.
    """
    target = (text or "").strip()
    if not target:
        return False
    if not (JUDGMENT_WORDS.search(target) and VAGUE_NOUNS.search(target)):
        return False
    if HAS_NUMBER.search(target):
        return False                      # 수치가 있으면 잴 수 있습니다
    if SEGMENT_WORDS.search(target):
        return False                      # 부문이라는 잴 대상이 있습니다
    for word, _ in ACCOUNT_WORDS:
        if word in target:
            return False                  # 계정이 있으면 잴 수 있습니다
    return True


REASON = (
    "무엇을 '좋다'고 할지 기준이 없는 평가 표현이라 참·거짓을 가릴 수 없습니다. "
    "의미 비교로 넘기면 함의와 모순이 동시에 높게 나와 근거가 되지 못합니다."
)
