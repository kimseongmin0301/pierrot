"""답변이 **스스로에 대해** 말한 문장을 가려냅니다.

왜 막아야 하는가
----------------
LLM 은 모르면 거부합니다. 그 거부 문장이 주장 분해를 거치면 회사 주장으로
둔갑합니다. 6단계 다듬기가 맥락을 채우며 **주체를 붙이기** 때문입니다.

실측(gpt-4o-mini 답변 40건):

    원문   "죄송하지만, SK하이닉스의 2024년 주가 상승률에 대한 정보를
            제공할 수 없습니다. 이미 종료된 기간이지만 ... 예측은 할 수 없습니다."

    주장1  "SK하이닉스는 이미 종료된 기간에 대한 실적이나 수치를 제공할 수 있다"
    주장2  "SK하이닉스는 미래에 대한 예측은 할 수 없다"

둘 다 **회사에 대한 사실 주장이 아닙니다.** 말하는 쪽의 사정입니다.
그런데 의미 비교 경로로 흘러가 사업보고서 문장과 견주어졌고, 모순 0.997 /
0.999 로 **모순 판정**이 났습니다. 공시에 그 답이 있을 리 없습니다.

`invented_company` / `invented_period` 와 같은 계열입니다. 다듬기가 원문에
없는 것을 채워 넣고, 그 흔적이 남지 않습니다. 다른 점은 채워 넣은 것이
회사명이나 연도가 아니라 **주어 전체**라는 것입니다.

무엇을 막고 무엇을 두는가
-------------------------
막는 것은 **정보 제공·답변 행위**에 대한 문장뿐입니다. 회사가 무엇을
공시했는가는 멀쩡한 사실 주장이므로 그대로 둡니다.

    막음: "SK하이닉스는 미래에 대한 예측은 할 수 없다"
    막음: "2024년 실적에 대한 정보를 제공할 수 없다"
    둠:   "SK하이닉스는 2024년 실적을 아직 공시하지 않았다"   (공시 여부는 사실)
    둠:   "SK하이닉스의 2024년 영업이익은 23조 원이다"
"""

from __future__ import annotations

import re

__all__ = ["is_meta_statement", "META_REASON"]

META_REASON = "답변이 스스로에 대해 말한 문장이라 공시로 가릴 대상이 아닙니다"

# 말하는 쪽의 행위. 회사의 사업 활동이 아닙니다.
_SPEECH_ACT = re.compile(
    r"정보를?\s*제공|자료를?\s*제공|수치를?\s*제공|답변(?:을|하)|말씀|설명해\s*드리"
    r"|예측(?:은|을|할)|추정(?:은|을|할)|알려\s*드리|확인해\s*드리|안내해\s*드리"
)

# 못 한다 / 할 수 있다 류의 가능 서술.
_ABILITY = re.compile(r"할\s*수\s*(?:없|있)|제공할\s*수\s*(?:없|있)|드릴\s*수\s*(?:없|있)|불가능")

# 사과·면책 투. 이것만으로도 메타 문장입니다.
_APOLOGY = re.compile(r"죄송|양해(?:를|해)|유의(?:하|해)\s*(?:시|주)|참고(?:만|로)\s*(?:하|해)")

# 회사가 실제로 한 행위는 사실 주장입니다. 가리면 손해입니다.
_CORPORATE_ACT = re.compile(
    r"공시|발표|보고서|사업보고서|분기보고서|기재|제출|승인|의결|배당|상장"
)


def is_meta_statement(text: str) -> bool:
    """답변 자신에 대한 문장이면 True.

    가려야 할지 애매하면 가리지 않습니다. 멀쩡한 사실 주장을 버리는 쪽이
    더 나쁩니다.
    """
    target = (text or "").strip()
    if not target:
        return False
    if _CORPORATE_ACT.search(target):
        return False          # 공시·발표 여부는 확인할 수 있는 사실입니다
    if _APOLOGY.search(target):
        return True
    return bool(_SPEECH_ACT.search(target) and _ABILITY.search(target))
