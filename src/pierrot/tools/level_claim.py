"""'N원으로 증가했다' — 금액이 적혀 있는데 방향만 보던 구멍을 막습니다.

실측 오탐(gpt-4o-mini 답변 40건, 참 판정 9건 중 2건)
---------------------------------------------------

    "신한지주의 2024년 순이익은 3조 5,000억 원으로 증가할 것으로 나타났다"
      -> 실제 연결 당기순이익 4조 5,581억원. 늘긴 늘었으므로 **근거 있음**.
         적힌 3조 5,000억 원은 아무도 확인하지 않았습니다. 1조가 틀렸습니다.

    "LG화학의 2023년 대비 매출은 15조 원으로 증가했다"
      -> 실제 연결 매출액 55조 2,497억원. 역시 늘었으므로 **근거 있음**.
         40조가 틀렸는데 통과했습니다.

13단계(한 문장에 사실이 여럿), 14단계(A에서 B로)와 같은 계열입니다.
**참인 일부로 더 강한 주장을 통과시키는** 실패입니다. 방향이 맞다고
금액까지 맞은 것이 아닙니다.

왜 프롬프트로 안 되는가
-----------------------
파서 프롬프트에는 이미 "DIRECTION 은 금액도 증감률도 적혀 있지 않을 때만"
이라고 적혀 있습니다(9단계). 그런데도 같은 문형이 DIRECTION 으로 떨어집니다.
지켜야 할 것은 코드로 검사합니다.

증감액 주장과 어떻게 가르는가
-----------------------------
    "매출이 1,000억 원 증가했다"      -> 늘어난 **폭**  (delta_claim 담당)
    "매출이 15조 원으로 증가했다"      -> 도달한 **값**  (여기 담당)

가르는 표시는 조사 '(으)로' 입니다. 이것이 없으면 손대지 않습니다.
잘못 집어 증감액을 값으로 견주면 터무니없는 모순이 납니다.
"""

from __future__ import annotations

import re

__all__ = ["detect"]

# 금액 표기. "3조 5,000억 원", "15조 원", "1조 3천억원" 을 한 덩이로 봅니다.
# '3천억' 처럼 천·백·십이 단위 앞에 끼는 표기를 받아야 합니다(amounts.py 와 같은 규칙).
_PART = r"\d[\d,]*(?:\.\d+)?\s*(?:천|백|십)?\s*(?:조|억|만)"
_AMOUNT = rf"{_PART}(?:\s*{_PART})*\s*원?"

# '(으)로' 뒤에 방향 말이 와야 값 주장입니다.
_UP = r"증가|상승|늘어|늘었|성장|개선|확대|증대|뛰"
_DOWN = r"감소|하락|줄어|줄었|축소|악화|둔화|후퇴"

LEVEL_PATTERN = re.compile(
    rf"({_AMOUNT})\s*(?:으로|로)\s*[^.]{{0,12}}?({_UP}|{_DOWN})"
)

# 증감률 주장은 GROWTH 가 맡습니다.
_PERCENT = re.compile(r"\d[\d,.]*\s*(?:%|퍼센트|%p|포인트)")

# 부문 주장은 전사 수치와 견주면 안 됩니다.
_SEGMENT = re.compile(r"부문|사업부|세그먼트|반도체|디스플레이|바이오시밀러|배터리")

# 숫자가 둘인 문장은 range_claim 이 양 끝을 둘 다 봅니다. 여기서 한쪽만 보면
# 나머지 한쪽의 거짓이 통과합니다.
_FROM_TO = re.compile(rf"{_AMOUNT}\s*에서\s*{_AMOUNT}\s*(?:으로|로)")


def detect(text: str) -> tuple[str, str]:
    """(금액 표기, 방향) 을 돌려줍니다. 값 주장이 아니면 ("", "").

    못 집으면 다른 경로가 받습니다. 잘못 집으면 거짓 판정이 납니다.
    그래서 조금이라도 애매하면 손대지 않습니다.
    """
    target = (text or "").strip()
    if not target:
        return "", ""
    if _FROM_TO.search(target):
        return "", ""          # 'A에서 B로' 는 range_claim 담당
    if _PERCENT.search(target):
        return "", ""          # 증감률이 적혀 있으면 GROWTH 담당
    if _SEGMENT.search(target):
        return "", ""          # 부문 수치는 전사 수치와 다릅니다

    match = LEVEL_PATTERN.search(target)
    if not match:
        return "", ""

    amount_text, word = match.group(1).strip(), match.group(2)
    direction = "UP" if re.fullmatch(_UP, word) else "DOWN"
    return amount_text, direction
