"""'N원으로 증가했다' — 금액이 적혀 있는데 방향만 보던 오탐을 고정합니다.

gpt-4o-mini 답변 40건의 참 판정 9건을 전수로 되짚다 나왔습니다.
9건 중 2건이 이 꼴이었습니다.

    "신한지주의 2024년 순이익은 3조 5,000억 원으로 증가할 것으로 나타났다"
      실제 연결 4조 5,581억원 -> 늘긴 늘어서 근거 있음. 1조가 틀렸는데도.

    "LG화학의 2023년 대비 매출은 15조 원으로 증가했다"
      실제 연결 55조 2,497억원 -> 역시 근거 있음. 40조가 틀렸는데도.

12/13/14단계와 같은 계열입니다. **참인 일부로 더 강한 주장을 통과시킴.**
"""

from __future__ import annotations

import pytest

from pierrot.tools.amounts import parse_korean_amount
from pierrot.tools.level_claim import detect


# ---------------------------------------------------------------------------
# 집어야 하는 것
# ---------------------------------------------------------------------------


@pytest.mark.parametrize(
    "text,amount,direction",
    [
        ("신한지주의 2024년 순이익은 3조 5,000억 원으로 증가할 것으로 나타났다",
         "3조 5,000억 원", "UP"),
        ("LG화학의 2023년 대비 매출은 15조 원으로 증가했다", "15조 원", "UP"),
        ("영업이익이 2조 원으로 감소했다", "2조 원", "DOWN"),
        ("매출액이 1조 3천억원으로 늘었다", "1조 3천억원", "UP"),
    ],
)
def test_값_주장을_집는다(text, amount, direction):
    found_amount, found_direction = detect(text)
    assert found_amount == amount
    assert found_direction == direction
    assert parse_korean_amount(found_amount) is not None, "금액으로 읽혀야 대조할 수 있습니다"


# ---------------------------------------------------------------------------
# 손대면 안 되는 것
# ---------------------------------------------------------------------------
#
# 잘못 집는 쪽이 못 집는 쪽보다 훨씬 나쁩니다. 못 집으면 다른 경로가 받지만,
# 잘못 집으면 엉뚱한 수치를 대조해 거짓 판정이 납니다.


@pytest.mark.parametrize(
    "text,why",
    [
        ("매출이 1,000억 원 증가했다", "늘어난 폭입니다. 값이 아니라 delta_claim 담당"),
        ("영업이익이 5,000억 원 감소했다", "같은 이유"),
        ("매출이 2조 원에서 3조 원으로 늘었다", "양 끝을 둘 다 봐야 합니다. range_claim 담당"),
        ("매출이 전년 대비 10% 증가했다", "증감률은 GROWTH 담당"),
        ("영업이익률이 5%p 상승했다", "같은 이유"),
        ("반도체 부문 매출이 10조 원으로 증가했다", "부문 수치는 전사 수치와 다릅니다"),
        ("영업이익이 크게 늘었다", "금액이 없으면 원래대로 방향 주장입니다"),
        ("매출이 증가했다", "같은 이유"),
        ("2024년 매출은 견조했다", "숫자도 방향도 없습니다"),
    ],
)
def test_손대지_않는다(text, why):
    assert detect(text) == ("", ""), why


def test_빈_문자열을_견딘다():
    assert detect("") == ("", "")
    assert detect(None) == ("", "")
