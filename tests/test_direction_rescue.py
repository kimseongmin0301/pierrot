def test_긴_계정_이름을_먼저_맞춘다():
    """'지배주주 순이익' 이 '순이익' 으로 잘못 잡히면 전혀 다른 값과 대조합니다."""
    assert find_account("KB금융의 지배주주 순이익이 늘었다") == "지배주주순이익"
    assert find_account("KB금융의 순이익이 늘었다") == "당기순이익"


def test_방향이_둘이면_판단하지_않는다():
    assert find_direction("매출은 늘었으나 이익은 줄었다") == ""
    assert find_direction("매출이 늘었다") == "UP"
    assert find_direction("매출이 줄었다") == "DOWN"
    assert find_direction("매출액") == ""
