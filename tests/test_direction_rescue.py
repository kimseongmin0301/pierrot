"""파서가 버린 방향 주장을 파이썬이 건져 내는 규칙.

왜 코드로 하는가: 재무 파서가 "구체적인 수치가 없다"며 방향 주장을 계속
OTHER 로 버립니다. 프롬프트에 여러 번 못박아도 **일관되지 않습니다.**
같은 형태인데 하나는 통과하고 하나는 버려졌습니다.

    "2025년에 매출이 지속적으로 상승하였다"  -> DIRECTION
    "2024년에 매출이 대폭 증가하였다"        -> OTHER  (같은 실행에서)

이 프로젝트는 같은 종류의 일을 세 번 겪었습니다.
다듬기가 없는 회사를 지어낸 건, 주장 개수를 줄인 건, 그리고 이 건입니다.
전부 **부탁을 검사로 바꿔서** 해결했습니다.

되살리지 못해 확인 불가로 남는 것보다 **잘못 되살려 거짓 판정을 내는 쪽이
훨씬 나쁩니다.** 그래서 조건을 하나라도 어기면 손대지 않습니다.
아래 테스트의 절반이 "손대지 않는다" 를 고정합니다.
"""

from __future__ import annotations

import pytest

from pierrot.tools.direction_rescue import find_account, find_direction, rescue


# ---------------------------------------------------------------------------
# 건져 내야 하는 것
# ---------------------------------------------------------------------------


@pytest.mark.parametrize(
    "text,account,direction",
    [
        ("SK하이닉스는 2025년에 매출이 지속적으로 상승하였다", "매출액", "UP"),
        ("SK하이닉스는 2024년에 매출이 대폭 증가하였다", "매출액", "UP"),
        ("SK하이닉스는 2026년 1분기에 영업이익이 높은 수준을 기록하였다", "영업이익", "UP"),
        ("삼성전자는 2023년에 순이익이 상승하였다", "당기순이익", "UP"),
        ("SK하이닉스는 2023년에 EPS가 부정적이었다", "주당순이익", "DOWN"),
        ("SK하이닉스는 2025년에 EPS가 크게 증가하였다", "주당순이익", "UP"),
        ("SK하이닉스는 2026년 1분기에 EPS가 긍정적인 흐름을 보였다", "주당순이익", "UP"),
        ("현대차는 2024년에 배당금 총액이 늘었다", "배당금총액", "UP"),
    ],
)
def test_수치_없는_방향_주장을_건져_낸다(text, account, direction):
    assert rescue(text) == (account, direction)


def test_흑자_적자는_방향이_아니라_부호다():
    """전에는 이 두 건을 방향 주장으로 건져 냈습니다. 그것이 틀렸습니다.

    '흑자 전환' 은 숫자가 늘었다는 뜻이 아니라 **부호가 바뀌었다**는 뜻입니다.
    증가로 읽으면 이미 흑자였던 해에도 통과합니다. 카카오 영업이익이
    +4,602억에서 +7,320억으로 늘었을 때 거짓 '근거 있음' 이 났습니다.

    이제 `turnaround` 가 부호로 판정합니다. 여기서는 손대지 않아야 합니다.
    """
    assert rescue("SK하이닉스는 2024년에 영업이익이 흑자로 전환되었다") == ("", "")
    assert rescue("SK하이닉스는 2023년에 영업이익이 적자를 기록하였다") == ("", "")


# ---------------------------------------------------------------------------
# 손대지 말아야 하는 것 — 이쪽이 더 중요합니다
# ---------------------------------------------------------------------------


@pytest.mark.parametrize(
    "text,why",
    [
        ("삼성전자의 2024년 매출은 300조 8,709억원이다", "금액이 적혀 있으면 파서의 AMOUNT 가 맞습니다"),
        ("현대차의 2024년 영업이익은 전년 대비 5.9% 증가했다", "증감률이 적혀 있으면 GROWTH 입니다"),
        ("NAVER의 2025년 영업이익은 2.2조원 수준이다", "'수준' 이 붙어도 금액입니다"),
        ("셀트리온의 2024년 백신 사업 매출이 늘었다", "부문 주장을 전사 수치와 견주면 안 됩니다"),
        ("SK하이닉스는 HBM 매출이 증가하였다", "HBM 은 부문입니다"),
        ("삼성전자의 광고 사업 부문 매출이 감소했다", "부문입니다"),
        ("삼성전자는 2023년에 매출은 늘었으나 영업이익은 줄었다", "방향이 둘이라 주장 하나로 다룰 수 없습니다"),
        ("삼성전자의 주가가 상승했다", "계정 낱말이 없습니다"),
        ("시장 여건이 개선되었다", "계정 낱말이 없습니다"),
        ("삼성전자의 2024년 매출액", "방향 낱말이 없습니다"),
        ("", "빈 문자열"),
    ],
)
def test_조건을_어기면_손대지_않는다(text, why):
    assert rescue(text) == ("", ""), why


@pytest.mark.parametrize(
    "text",
    [
        "셀트리온의 2024년 1분기 매출 증가의 주된 원인은 미국 수요 증가이다",
        "삼성전자의 반도체 부문 실적 개선이 전체 영업이익 성장을 견인했다",
        "중국 시장의 부진이 현대차의 영업이익 감소에 영향을 미쳤다",
        "환율 변동 덕분에 매출이 늘었다",
        "금리 인상으로 인해 순이익이 줄었다",
    ],
)
def test_인과_주장은_손대지_않는다(text):
    """실측 오탐을 고정합니다.

    "매출 증가의 주된 원인은 미국 수요 증가이다" 를 방향 주장으로 되살렸고,
    매출이 실제로 늘었으므로 '근거 있음' 이 났습니다.
    **원인이 무엇인지는 아무것도 확인하지 않았습니다.**
    참인 부분이 들어 있다고 주장 전체가 참이 되지 않습니다.
    """
    assert rescue(text) == ("", "")


